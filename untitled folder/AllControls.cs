/*
    Movement Controls
    W, A, S, D: Move
    Mouse: Look around
    Left Shift: Sprint(hold while moving forward)
    Crouch and Slide
    Left Control: Crouch(hold)
    Left Control + Left Shift (while moving fast): Slide

    Slide only works if:

    You are grounded
    You are moving fast enough
    Jump
    Spacebar: Jump

    Jump only works when:

    You are grounded
    You are not crouching or sliding
    Camera Controls
    Mouse X: Turn player left and right
    Mouse Y: Look up and down

    Camera behavior:

    Lowers when crouching
    Lowers further when sliding
    Returns to normal when standing
    FOV increases when sprinting
*/